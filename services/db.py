def get_db():
    # เธเธทเธเธญเธญเธเน€เธเนเธเธ•เนเธเธฒเธเธเนเธญเธกเธนเธฅ เนเธ”เธขเน€เธฅเธทเธญเธเนเธเน MongoDB เธซเธฒเธเธ•เธฑเนเธเธเนเธฒเธเธฃเนเธญเธก เนเธกเนเน€เธเนเธเธเธฑเนเธเนเธเนเธเธฅเธฑเธเธเนเธญเธกเธนเธฅเธเธณเธฅเธญเธ
    global _client, _db
    if _db is None:
        if _should_use_mongo():
            if MongoClient is None:
                raise RuntimeError("pymongo is required when MONGO_URI is set")
            try:
                _client = MongoClient(Config.MONGO_URI)
                _db = _client[Config.DB_NAME]
                _db.conversations.create_index([("user_id", 1), ("updated_at", -1)])
                _db.characters.create_index([("key", 1)], unique=True)
            except ConfigurationError as exc:
                logging.getLogger(__name__).warning("Mongo configuration error: %s", exc)
                _client = None
                _db = InMemoryDB()
            except Exception as exc:
                logging.getLogger(__name__).warning("Mongo connection failed: %s", exc)
                _client = None
                _db = InMemoryDB()
        else:
            _db = InMemoryDB()
    return _db





